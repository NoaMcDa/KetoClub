/// Diets: the trigger vocabulary of vegan, vegetarian and keto
/// (Banto; ALG-01, issue #343).
///
/// Every term comes from
/// `allergen app documentation/11_hidden_allergen_sources.md` or
/// `12_israeli_and_us_menu_lexicon.md` and its source cites the section
/// (`"11 §11"`, `"12 §1.1"`), which
/// `test/utils/allergens/vocabulary_test.dart` checks. After a change,
/// regenerate the goldens and copy `allergens.json` to
/// `backend/app/keto/` (architecture.md D26).
///
/// A diet is flexible (`RestrictionKind.lifestyle`): a hit here means "the
/// text names an ingredient a vegan / vegetarian does not eat", never a
/// safety claim, and the terms favour the clear case over every plant
/// look-alike. The vocabulary is **one list per restriction**, and a guard
/// applies to every trigger of that restriction, so a plant adjective
/// ("oat", "coconut", "almond") is not a guard here: it would also lower
/// "coconut shrimp" and "almond chicken". The words that are ambiguous in
/// that way (milk, butter, cream, and their Hebrew twins) are therefore
/// listed `likely` rather than stated. Only the restaurant's own
/// declaration (vegan, plant based, טבעוני, צמחוני ...) and the word "no"
/// lower a hit to `suspected`; no guard cancels one (ALG-04a). The plant
/// emoji is not a guard: `TextNormaliser.normalise` deletes it, so a
/// phrase made of it normalises to nothing.
///
/// `keto` stays empty for good: its vocabulary lives in
/// `lib/utils/constants.dart` and the rule engine.
///
/// `בשר`, `עוף`, `בקר` and `כבש` are listed without the permissive Hebrew
/// prefix because `לבשר` ("to announce"), `מעוף` ("flight"), `לבקר` ("to
/// visit") and `מכבש` ("press") would otherwise read as food; their
/// prefixed food forms (`הבשר`, `ובשר`, `בעוף` ...) are terms of their own.
/// `הפוך` ("latte") is listed that way too, as the keto vocabulary does,
/// because `להפוך` means "to flip".
