/// The extended restrictions' trigger vocabulary: alpha-gal, FODMAP,
/// histamine and small portions for GLP-1 eating, plus the user's own
/// free-text restriction (Banto; the Allergens epic, ALG-17, issue #359).
///
/// Every term comes from
/// `allergen app documentation/11_hidden_allergen_sources.md` (§17, §21–§23)
/// or `12_israeli_and_us_menu_lexicon.md` (§7) and its source cites the
/// section, which `test/utils/allergens/vocabulary_test.dart` checks. After a
/// change, regenerate the goldens and copy `allergens.json` to
/// `backend/app/keto/` (architecture.md D26).
///
/// Alpha-gal is an allergen and its certainties are honest: a dish that
/// names a mammal meat is stated, a burger or a kebab that may be chicken is
/// likely, a sausage casing or a stock is suspected. Dairy, which some people
/// with alpha-gal syndrome react to, is not listed: the Milk restriction
/// carries it, and the person adds that entry too.
///
/// FODMAP, histamine and GLP-1 are heads-up restrictions
/// (`headsUpRestrictions` in `taxonomy.dart`): a menu never states a dose, so
/// `ProfileEvaluator` reads every concern of theirs as "may be high in …",
/// whatever its certainty here. Their direct terms are still the foods a
/// menu names, and GLP-1, which no food "names", has hidden cues only.
///
/// [RestrictionId.custom] is permanently empty here: its terms are the
/// user's own, kept in the profile on the device (D26 C1), and
/// `custom_terms.dart` compiles them there.
