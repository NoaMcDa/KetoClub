#!/usr/bin/env bash
# Writes the entry file for one shard of the flow tests (issue #453).
#
# CI used to run `flutter drive` once per flow file, and every call compiled
# the whole app for the web and started Chrome again: about 50 s a file, 3 s
# of it testing. A shard's entry imports its share of the flow files and runs
# each one's main() in a group, so a machine compiles once and drives them
# all; the shards run on parallel machines.
#
# Usage:
#   tool/flow_shard.sh <index> <count>   write the entry for shard <index>
#                                        (0-based) of <count>, print its path
#   tool/flow_shard.sh --verify <count>  check that every flow file lands in
#                                        exactly one of <count> shards
#
# A flow file is integration_test/flows/*_flow_test.dart. Files are dealt out
# round-robin in sorted order (LC_ALL=C), so a shard's set is stable and the
# shards stay within one file of each other. The entry sits beside the flows
# and imports them by bare file name: `flutter drive` roots the compile at the
# target's own directory (CLAUDE.md, "A web flow test's imports"). Generated
# entries are ignored by git and never edited by hand.
set -euo pipefail
cd "$(dirname "$0")/.."

flows_dir="integration_test/flows"

flow_files() {
  find "$flows_dir" -maxdepth 1 -name '*_flow_test.dart' -printf '%f\n' |
    LC_ALL=C sort
}

# The files of shard $1 of $2, one per line.
shard_files() {
  local index="$1" count="$2" i=0
  while IFS= read -r file; do
    if (( i % count == index )); then echo "$file"; fi
    i=$((i + 1))
  done < <(flow_files)
}

check_count() {
  if ! [[ "$1" =~ ^[1-9][0-9]*$ ]]; then
    echo "flow_shard.sh: the shard count must be a positive integer, got '$1'" >&2
    exit 2
  fi
}

if [[ "${1:-}" == "--verify" ]]; then
  count="${2:-}"
  check_count "$count"
  all="$(flow_files)"
  if [[ -z "$all" ]]; then
    echo "flow_shard.sh: no flow files under $flows_dir" >&2
    exit 1
  fi
  dealt="$(for ((s = 0; s < count; s++)); do shard_files "$s" "$count"; done | LC_ALL=C sort)"
  if [[ "$dealt" != "$all" ]]; then
    echo "flow_shard.sh: the shards do not cover every flow file exactly once" >&2
    diff <(echo "$all") <(echo "$dealt") >&2 || true
    exit 1
  fi
  # An integration test that is not a top-level flows/*_flow_test.dart is
  # driven by no shard (issue #459). The generated shard entries are exempt.
  stray="$(find integration_test -name '*_test.dart' ! -name 'flow_shard_*_test.dart' |
    LC_ALL=C sort | grep -vxE "$flows_dir/[^/]+_flow_test\.dart" || true)"
  if [[ -n "$stray" ]]; then
    echo "flow_shard.sh: no shard drives these; put each in $flows_dir/ named"          "*_flow_test.dart:" >&2
    echo "$stray" >&2
    exit 1
  fi
  for ((s = 0; s < count; s++)); do
    if [[ -z "$(shard_files "$s" "$count")" ]]; then
      echo "flow_shard.sh: shard $s of $count is empty; use fewer shards" >&2
      exit 1
    fi
  done
  echo "flow_shard.sh: $(echo "$all" | wc -l | tr -d ' ') flow files in $count shards, each exactly once"
  exit 0
fi

index="${1:-}"
count="${2:-}"
check_count "$count"
if ! [[ "$index" =~ ^[0-9]+$ ]] || (( index >= count )); then
  echo "flow_shard.sh: the shard index must be 0 to $((count - 1)), got '$index'" >&2
  exit 2
fi

mapfile -t files < <(shard_files "$index" "$count")
if [[ ${#files[@]} -eq 0 ]]; then
  echo "flow_shard.sh: shard $index of $count has no flow files" >&2
  exit 1
fi

out="$flows_dir/flow_shard_${index}_test.dart"
{
  echo "// GENERATED by tool/flow_shard.sh $index $count (issue #453)."
  echo "// Do not edit or commit: CI writes it before driving this shard."
  echo
  echo "import 'package:flutter_test/flutter_test.dart';"
  echo "import 'package:integration_test/integration_test.dart';"
  echo
  for i in "${!files[@]}"; do
    echo "import '${files[$i]}' as flow_$i;"
  done
  echo
  echo "void main() {"
  echo "  IntegrationTestWidgetsFlutterBinding.ensureInitialized();"
  for i in "${!files[@]}"; do
    echo "  group('${files[$i]%.dart}', flow_$i.main);"
  done
  echo "}"
} > "$out"

echo "$out"
printf '  %s\n' "${files[@]}" >&2
